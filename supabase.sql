-- Ejecuta este SQL en Supabase > SQL Editor > New query.
create table if not exists public.racing_scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 2 and 18),
  score integer not null check (score >= 0),
  duration_seconds integer not null default 45 check (duration_seconds between 1 and 300),
  created_at timestamptz not null default now()
);

alter table public.racing_scores enable row level security;

-- Cualquiera puede leer la tabla pública de récords.
create policy "Anyone can read racing scores"
on public.racing_scores for select
to anon, authenticated
using (true);

-- Los visitantes pueden añadir su resultado. No se permite editar ni borrar récords.
create policy "Anyone can add racing scores"
on public.racing_scores for insert
to anon, authenticated
with check (
  char_length(player_name) between 2 and 18
  and score >= 0
  and duration_seconds between 1 and 300
);
